"""A11/A12 diagnostics through fixed Web Host and loopback Messages transport.

The caller owns ``boundary`` and must serialize these scenarios with other A
cases. This module never reads credentials and refuses a non-A boundary. Its
diagnostic profiles are confined to the ignored run directory; the learning
profile and upstream artifact remain unchanged.
"""
from __future__ import annotations

import asyncio
import copy
import json
from pathlib import Path
import time
from typing import Any


ROOT = Path(__file__).resolve().parent
SNAPSHOT = (
    "CURRENT_PROBLEM_SNAPSHOT revision=2. Numerator is sin(x)-x*cos(x). "
    "The user explicitly corrected the denominator to 2*x^3; all other "
    "conditions are unchanged, x approaches zero. The attached approved "
    "synthetic M01 image supplies the original diagram; this correction "
    "overrides its denominator. Explain the corrected problem."
)


def _save(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")


async def _wait(predicate, timeout: float = 20) -> Any:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        value = predicate()
        if value:
            return value
        await asyncio.sleep(0.025)
    raise TimeoutError("A11_A12_EXPECTED_EVENT_NOT_OBSERVED")


def _events(peer, stream: str, offset: int = 0) -> list[dict]:
    return [row["wire"]["value"]["event"]
            for row in peer.streams[stream][offset:]
            if row["wire"].get("value", {}).get("type") == "event"]


async def _turn(peer, sid: str, stream: str, text: str, image=None) -> dict:
    offset = len(peer.streams[stream])
    receipt = await peer.prompt(sid, text, image)
    await _wait(lambda: any(event["type"] == "turn/end"
                           for event in _events(peer, stream, offset)), 30)
    await asyncio.sleep(0.15)
    return {"receipt": receipt, "events": _events(peer, stream, offset)}


def _request(boundary, row: dict) -> dict:
    path = boundary.private / (row["request_id"] + ".request.json")
    return json.loads(path.read_text(encoding="utf-8"))


def _image_digest(row: dict) -> str | None:
    if not row.get("images"):
        return None
    image = row["images"][-1]
    return image.get("sha256") or image.get("resolved_sha256")


def _make_patch(folder: Path, overrides: dict[str, dict]) -> Path:
    rows = json.loads((ROOT / "profile/cordis.patch.json").read_text(encoding="utf-8"))
    for identity, updates in overrides.items():
        row = next((row for row in rows if row.get("id") == identity), None)
        if row is None:
            row = {"id": identity}
            rows.append(row)
        # Config patch rows replace upstream config, so preserve the full
        # learning-provider config before applying diagnostic field overrides.
        for key, value in updates.items():
            if key == "config":
                row["config"] = {**row.get("config", {}), **copy.deepcopy(value)}
            else:
                row[key] = copy.deepcopy(value)
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / "diagnostic.patch.json"
    _save(path, rows)
    return path


def _model_override(**changes) -> dict:
    rows = json.loads((ROOT / "profile/cordis.patch.json").read_text(encoding="utf-8"))
    provider = next(row for row in rows if row.get("id") == "llm-deepseek")
    models = copy.deepcopy(provider["config"]["models"])
    for model in models:
        if model["id"] == "deepseek-flash":
            model.update(changes)
    return {"models": models}


async def run_context_cases(run_dir, boundary, Host, Peer, patch_builder=None):
    """Return A11/A12 rows, recording each diagnostic and cleanup separately.

    Optional ``patch_builder(folder, overrides)`` may replace the local patch
    writer. It must return a template path accepted by ``Host(..., patch)``.
    This function owns its diagnostic Hosts, not the supplied boundary server.
    """
    if boundary.mode != "A" or boundary.actual_outbound_attempts != 0:
        raise ValueError("A11_A12_REQUIRE_ZERO_OUTBOUND_A_BOUNDARY")
    directory = Path(run_dir) / "context-diagnostics"
    directory.mkdir(parents=True, exist_ok=True)
    image = Path(run_dir) / "private/samples/M01.png"
    if not image.is_file():
        from samples import generate
        image = Path(generate(run_dir)["M01"]["path"])
    diagnostics: list[dict] = []
    builder = patch_builder or _make_patch

    async def execute(label, overrides, action):
        folder = directory / label
        patch = builder(folder, overrides)
        host = Host(folder / "host", boundary.url, patch)
        # Loopback capability is generated by the fixture, never a real key.
        host.env["DEEPSEEK_API_KEY"] = boundary.local_token
        peer = None
        before = len(boundary.records)
        files_before = len(boundary.file_records)
        observation = {"diagnostic": label, "assertions": {}, "observations": {}}
        try:
            # Start is bounded by Host and owns exactly its Windows Job.
            await asyncio.to_thread(host.start)
            peer = await Peer(host).connect()
            await action(host, peer, observation)
        except Exception as error:
            observation["error"] = {"type": type(error).__name__, "message": str(error)}
            observation["assertions"]["diagnostic_completed"] = False
        finally:
            try:
                if peer:
                    _save(folder / "private/peer-frames.json", peer.frames)
                    await peer.close()
            except Exception as error:
                observation["peer_cleanup_error"] = {"type": type(error).__name__, "message": str(error)}
                observation["assertions"]["peer_closed"] = False
            finally:
                await asyncio.to_thread(host.stop)
            observation["requests"] = boundary.records[before:]
            observation["files"] = boundary.file_records[files_before:]
            observation["cleanup"] = host.cleanup
            observation["real_model_attempts"] = boundary.actual_outbound_attempts
            observation["assertions"]["zero_real_model_attempts"] = boundary.actual_outbound_attempts == 0
            observation["assertions"]["owned_host_cleaned"] = (
                host.cleanup.get("remaining_job_pids") == []
                and host.cleanup.get("host_port_closed") is True)
            observation["status"] = "passed" if all(observation["assertions"].values()) else "failed"
            _save(folder / "result.json", observation)
            diagnostics.append(observation)
            print(json.dumps({"diagnostic": label, "status": observation["status"]}), flush=True)

    async def pressure_action(host, peer, report):
        sid, stream = await peer.create("v1-a11-pressure")
        boundary.set_scenario(text_chunks=["Short synthetic checkpoint."], delay=0.01)
        filler = " Synthetic obsolete background abcdefghijklmnopqrstuvwxyz." * 450
        first = await _turn(peer, sid, stream, "Original current problem: M01." + filler, image)
        approved_request_image_digest = _image_digest(boundary.records[-1])
        second = await _turn(peer, sid, stream, "Correction: denominator is 2*x^3, all else unchanged.")
        events_before_protection = _events(peer, stream)
        compactions = [event for event in events_before_protection if event["type"] == "compaction/end"]
        before = len(boundary.records)
        protected = await _turn(peer, sid, stream, SNAPSHOT, image)
        final = boundary.records[-1]
        body = _request(boundary, final)
        final_content = json.dumps(body["messages"], ensure_ascii=False)
        summary_requests = [row for row in boundary.records
                            if row["received_ns"] >= first["events"][0]["time"] * 1000000
                            and row.get("max_tokens") == 128]
        report["assertions"].update({
            "automatic_compaction_executed": bool(compactions),
            "compaction_succeeded": any(not event.get("data", {}).get("error") for event in compactions),
            "auxiliary_summary_reached_boundary": bool(summary_requests),
            "protected_followup_dispatched": len(boundary.records) > before,
            "current_snapshot_in_actual_request": SNAPSHOT in final_content,
            "current_corrected_condition_in_request": "2*x^3" in final_content,
            "current_confirmed_image_in_request": len(final["images"]) >= 1,
            "request_image_matches_approved_normalized_image": bool(approved_request_image_digest)
                and _image_digest(final) == approved_request_image_digest,
        })
        report["observations"] = {"session_id": sid,
            "compaction_events": [event for event in _events(peer, stream) if event["type"].startswith("compaction/")],
            "first_submission": first["receipt"], "corrected_submission": second["receipt"],
            "protected_submission": protected["receipt"], "final_request_id": final["request_id"],
            "final_images": final["images"], "summary_request_ids": [row["request_id"] for row in summary_requests],
            "protection_method": "durable prompt from runner-owned current-problem snapshot; no frozen LLM rewrite"}

    await execute("A11-pressure-and-snapshot", {
        "llm-deepseek": {"config": {"maxTokens": 256,
            **_model_override(contextWindow=4096, maxTokens=256)}},
        "compaction-basic": {"disabled": False, "config": {"auto": True,
            "thresholdRatio": 0.2, "headroomTokens": 64, "retainTokens": 0,
            "maxTokens": 128, "compactionRetries": 0, "maxOverflowRetries": 0}},
    }, pressure_action)

    async def offload_action(host, peer, report):
        sid, stream = await peer.create("v1-a11-offload")
        boundary.set_scenario(text_chunks=["One approved image retained."], delay=0.01)
        original = await _turn(peer, sid, stream, "Original current problem M01.", image)
        approved_request_image_digest = _image_digest(boundary.records[-1])
        current = await _turn(peer, sid, stream, SNAPSHOT, image)
        final = boundary.records[-1]
        body = _request(boundary, final)
        events = _events(peer, stream)
        offloads = [event for event in events if event["type"] == "image/offload"]
        report["assertions"].update({
            "durable_offload_executed": bool(offloads),
            "latest_image_survives_single_image_budget": len(final["images"]) == 1,
            "latest_image_matches_approved_normalized_image": bool(approved_request_image_digest)
                and _image_digest(final) == approved_request_image_digest,
            "current_conditions_survive": SNAPSHOT in json.dumps(body["messages"], ensure_ascii=False),
            "no_summary_dispatched": all(row.get("max_tokens") != 128 for row in boundary.records
                                         if row["received_ns"] >= original["events"][0]["time"] * 1000000),
        })
        report["observations"] = {"session_id": sid, "offload_events": offloads,
            "original_submission": original["receipt"], "current_submission": current["receipt"],
            "final_request_id": final["request_id"], "final_images": final["images"],
            "same_confirmed_attachment_new_occurrence": True}

    await execute("A11-offload-current-occurrence", {
        "llm-deepseek": {"config": {"maxImagesPerRequest": 1, "imageOffloadCountQuantum": 1}},
        "compaction-basic": {"config": {"auto": False}},
        "image-offload": {"disabled": False},
    }, offload_action)

    async def title_action(host, peer, report):
        sid, stream = await peer.create("v1-a12-title")
        boundary.set_scenario(text_chunks=["Synthetic title"], delay=0.01)
        before = len(boundary.records)
        turn = await _turn(peer, sid, stream, "Find the limit of a synthetic example.")
        await _wait(lambda: len(boundary.records) >= before + 2)
        await _wait(lambda: any(event["type"] == "session/title-llm-request" for event in _events(peer, stream)))
        rows = boundary.records[before:]
        report["assertions"].update({"title_and_main_both_counted": len(rows) == 2,
            "title_cap_identifies_auxiliary_request": any(row["max_tokens"] == 32 for row in rows),
            "durable_auxiliary_request_attributed": any(event["type"] == "session/title-llm-request" for event in _events(peer, stream))})
        report["observations"] = {"submission": turn["receipt"],
            "auxiliary_events": [event for event in _events(peer, stream) if event["type"].startswith("session/title")],
            "request_ids": [row["request_id"] for row in rows]}

    await execute("A12-title", {"session-title-llm": {"disabled": False,
        "config": {"targetWords": 5, "targetCjkCharacters": 10, "maxInputBytes": 4096,
                   "maxOutputTokens": 32, "timeoutMs": 5000,
                   "provider": "deepseek-official", "model": "deepseek-flash"}},
        "compaction-basic": {"config": {"auto": False}}}, title_action)

    retry_config = {"mode": "normal", "maxRetries": 1, "retryableCodes": ["SERVER"],
                    "backoff": {"initialDelayMs": 1, "maxDelayMs": 1, "jitterRatio": 0}}

    async def retry_action(host, peer, report):
        sid, stream = await peer.create("v1-a12-retry")
        boundary.set_scenario(fault="http_500", fault_once=True, text_chunks=["Retry fixture settled."], delay=0.01)
        before = len(boundary.records)
        turn = await _turn(peer, sid, stream, "Explicit diagnostic transient retry.")
        rows = boundary.records[before:]
        report["assertions"].update({"both_actual_dispatches_counted": len(rows) == 2,
            "first_failed_second_completed": len(rows) == 2 and rows[0]["status"] == "fixture_http_500" and rows[1]["status"] == "completed",
            "durable_retry_recorded": any(event["type"] == "llm/retry" for event in _events(peer, stream))})
        report["observations"] = {"submission": turn["receipt"], "events": _events(peer, stream),
                                  "diagnostic_only_retry_policy": retry_config}

    await execute("A12-explicit-retry-diagnostic", {
        "llm-deepseek": {"config": {"retryPolicy": retry_config}},
        "compaction-basic": {"config": {"auto": False}},
    }, retry_action)

    async def no_retry_action(host, peer, report):
        sid, stream = await peer.create("v1-a12-no-retry")
        boundary.set_scenario(fault="http_500", fault_once=True)
        before = len(boundary.records)
        await _turn(peer, sid, stream, "Learning combination must not retry an unknown failure.")
        await asyncio.sleep(0.4)
        rows = boundary.records[before:]
        report["assertions"].update({"learning_combination_single_dispatch": len(rows) == 1,
            "no_durable_retry": not any(event["type"] == "llm/retry" for event in _events(peer, stream))})

    await execute("A12-learning-no-retry", {
        "compaction-basic": {"config": {"auto": False}},
    }, no_retry_action)

    async def files_action(host, peer, report):
        sid, stream = await peer.create("v1-a12-file-expired")
        boundary.set_scenario(fault="file_expired_once", text_chunks=["Replacement completed."], delay=0.01)
        before, files_before = len(boundary.records), len(boundary.file_records)
        turn = await _turn(peer, sid, stream, "Approved image with controlled remote file expiry.", image)
        rows = boundary.records[before:]
        uploads = [row for row in boundary.file_records[files_before:] if row["method"] == "POST" and row.get("file_id")]
        file_ids = [row["images"][0].get("file_id") for row in rows if row["images"]]
        report["assertions"].update({"provider_internal_replacement_counted": len(rows) == 2,
            "two_distinct_file_uploads": len(uploads) == 2 and uploads[0]["file_id"] != uploads[1]["file_id"],
            "replacement_uses_new_file": len(file_ids) == 2 and file_ids[0] != file_ids[1],
            "second_dispatch_completes": len(rows) == 2 and rows[-1]["status"] == "completed"})
        report["observations"] = {"submission": turn["receipt"], "file_ids": file_ids,
            "retry_policy": {"mode": "normal", "maxRetries": 0},
            "note": "provider-owned file replacement occurs inside one llm.stream call"}

    await execute("A12-provider-file-replacement", {
        "compaction-basic": {"config": {"auto": False}},
    }, files_action)

    async def budget_action(host, peer, report):
        sid, stream = await peer.create("v1-a12-budget")
        boundary.set_scenario(fault="file_expired_once", local_request_limit=1,
                              text_chunks=["This must never dispatch locally."], delay=0.01)
        before = len(boundary.records)
        await _turn(peer, sid, stream, "Independently block a hidden provider replacement at the boundary.", image)
        rows = boundary.records[before:]
        report["assertions"].update({"replacement_reached_independent_guard": len(rows) == 2,
            "second_dispatch_blocked_at_boundary": len(rows) == 2 and rows[-1]["status"] == "local_budget_blocked",
            "blocked_request_not_generated": len(rows) == 2 and not rows[-1].get("terminal_emitted_ns")})
        report["observations"] = {"limit_kind": "A-only local fixture response dispatch limit",
            "real_model_limit": 0, "local_fixture_limit": 1,
            "request_ids": [row["request_id"] for row in rows],
            "ledger_ref": str(boundary.ledger.path)}

    await execute("A12-independent-boundary-budget", {
        "compaction-basic": {"config": {"auto": False}},
    }, budget_action)

    result = []
    for case, prefixes in [("V1-A11", ("A11-",)), ("V1-A12", ("A12-", "A11-pressure"))]:
        selected = [item for item in diagnostics if item["diagnostic"].startswith(prefixes)]
        assertions = {item["diagnostic"]: item["status"] == "passed" for item in selected}
        row = {"case_id": case, "status": "passed" if all(assertions.values()) else "failed",
               "assertions": assertions, "observations": selected,
               "real_model_attempts": boundary.actual_outbound_attempts}
        result.append(row)
        _save(Path(run_dir) / "cases" / (case + ".json"), row)
    _save(directory / "results.json", result)
    return result
